// Shared "car rig" helpers used by the convert-*.mjs scripts.
//
// Pipeline (sources in ~/.zcode/workspace/default/crimson-coast/car-models, see
// LICENSES.md there; run from this folder after npm install; build/ is scratch):
//   rossini-9x   npx gltf-transform copy <porsche-911>/911-transformed.glb build/911-decoded.glb
//                (Draco decode), then node convert-911.mjs
//   vector-gt    node convert-carconcept.mjs
//   volt3        node convert-tesla.mjs (-> build/volt3-raw.glb), node convert-finish.mjs volt3
//   courier-van  node convert-sprinter.mjs (-> build/courier-van-raw.glb), node convert-finish.mjs courier-van
//   gz-*         blender -b --python batch_gazebo.py -- <gazebo-set> build/gz, then node convert-gazebo.mjs
//   check        node inspect.mjs ../../public/game/assets/models/<file>.glb [--tree]
//
// Every realistic car GLB the game loads follows one layout (read by
// assets.js realTemplate):
//   - real-world metres, facing +Z, +X = the car's left, tyres touching y = 0,
//     centred on x/z
//   - one unnamed body mesh per material (joined)
//   - one node per wheel, named wheel_fl / wheel_fr / wheel_rl / wheel_rr
//     (extra rear axles: wheel_rl2 / wheel_rr2 ...), node translation = wheel
//     centre, geometry centred on the node with the axle along X (front wheels
//     that were modelled steered are rotated straight)
//   - non-spinning wheel parts (calipers, brake pads) stay in the body
//   - recolourable body paint material is named 'paint'; nothing else may
//     contain 'paint' in its name
//   - plain glTF 2.0: no extensions (no Draco/meshopt/KTX2/webp), textures are
//     embedded PNG (alpha) or JPEG (opaque), <= 1024 px
import { Document } from '@gltf-transform/core';
import { flatten, clearNodeTransform, join, prune, dedup, weld, simplifyPrimitive } from '@gltf-transform/functions';
import { MeshoptSimplifier } from 'meshoptimizer';
import sharp from 'sharp';

// ---------------------------------------------------------------- geometry
// Bake every node transform into its mesh so all geometry is in model space
// directly under the scene root.
export async function bakeAll(doc) {
  await doc.transform(flatten());
  for (const n of doc.getRoot().listNodes()) {
    if (n.getMesh()) {
      // meshes shared by several nodes must be cloned before baking
      const users = doc.getRoot().listNodes().filter((o) => o.getMesh() === n.getMesh());
      if (users.length > 1) n.setMesh(n.getMesh().clone());
      clearNodeTransform(n);
    }
  }
  // drop empty transform-only nodes
  for (const n of doc.getRoot().listNodes()) if (!n.getMesh() && !n.listChildren().length) n.dispose();
}

function triCount(prim) {
  const idx = prim.getIndices();
  return (idx ? idx.getCount() : prim.getAttribute('POSITION').getCount()) / 3;
}
function triVerts(prim, t, out) {
  const idx = prim.getIndices();
  for (let k = 0; k < 3; k++) out[k] = idx ? idx.getScalar(3 * t + k) : 3 * t + k;
  return out;
}

// New primitive holding only the triangles where keep[t] is truthy.
export function subsetPrimitive(doc, prim, keep) {
  const buffer = doc.getRoot().listBuffers()[0];
  const nTri = triCount(prim);
  const vCount = prim.getAttribute('POSITION').getCount();
  const remap = new Int32Array(vCount).fill(-1);
  const order = [];
  const idx = [];
  const tv = [0, 0, 0];
  for (let t = 0; t < nTri; t++) {
    if (!keep[t]) continue;
    triVerts(prim, t, tv);
    for (const v of tv) {
      if (remap[v] < 0) { remap[v] = order.length; order.push(v); }
      idx.push(remap[v]);
    }
  }
  if (!idx.length) return null;
  const out = doc.createPrimitive().setMaterial(prim.getMaterial()).setMode(prim.getMode());
  for (const sem of prim.listSemantics()) {
    if (sem === 'TANGENT') continue; // regenerated by the renderer if needed
    const src = prim.getAttribute(sem);
    const size = src.getElementSize();
    const Arr = src.getArray().constructor;
    const arr = new Arr(order.length * size);
    const el = new Array(size);
    for (let i = 0; i < order.length; i++) {
      src.getElement(order[i], el);
      for (let k = 0; k < size; k++) arr[i * size + k] = el[k];
    }
    out.setAttribute(sem, doc.createAccessor().setType(src.getType()).setArray(arr).setNormalized(src.getNormalized()).setBuffer(buffer));
  }
  out.setIndices(doc.createAccessor().setType('SCALAR').setArray(new Uint32Array(idx)).setBuffer(buffer));
  return out;
}

function primBounds(prim, mn = [1e9, 1e9, 1e9], mx = [-1e9, -1e9, -1e9]) {
  const pos = prim.getAttribute('POSITION');
  const e = [0, 0, 0];
  for (let i = 0; i < pos.getCount(); i++) {
    pos.getElement(i, e);
    for (let k = 0; k < 3; k++) { mn[k] = Math.min(mn[k], e[k]); mx[k] = Math.max(mx[k], e[k]); }
  }
  return [mn, mx];
}
export function docBounds(doc) {
  const mn = [1e9, 1e9, 1e9], mx = [-1e9, -1e9, -1e9];
  for (const n of doc.getRoot().listNodes()) {
    const mesh = n.getMesh();
    if (!mesh) continue;
    const t = n.getTranslation();
    for (const p of mesh.listPrimitives()) {
      const [a, b] = primBounds(p, [1e9, 1e9, 1e9], [-1e9, -1e9, -1e9]);
      for (let k = 0; k < 3; k++) { mn[k] = Math.min(mn[k], a[k] + t[k]); mx[k] = Math.max(mx[k], b[k] + t[k]); }
    }
  }
  return [mn, mx];
}

// Rotate (about Y, around c) then translate by d, positions and normals in place.
function moveVerts(prim, c, yaw, d) {
  const cs = Math.cos(yaw), sn = Math.sin(yaw);
  const pos = prim.getAttribute('POSITION');
  const nor = prim.getAttribute('NORMAL');
  const e = [0, 0, 0];
  for (let i = 0; i < pos.getCount(); i++) {
    pos.getElement(i, e);
    const x = e[0] - c[0], z = e[2] - c[2];
    pos.setElement(i, [cs * x + sn * z + c[0] + d[0], e[1] + d[1], -sn * x + cs * z + c[2] + d[2]]);
  }
  if (nor) for (let i = 0; i < nor.getCount(); i++) {
    nor.getElement(i, e);
    nor.setElement(i, [cs * e[0] + sn * e[2], e[1], -sn * e[0] + cs * e[2]]);
  }
}

// Yaw of a wheel's axle away from the X axis: the axle is the horizontal
// direction with the least vertex spread (a tyre is wide, not thick).
function axleYaw(prims) {
  let n = 0, sx = 0, sz = 0;
  const e = [0, 0, 0];
  for (const p of prims) { const pos = p.getAttribute('POSITION'); for (let i = 0; i < pos.getCount(); i++) { pos.getElement(i, e); sx += e[0]; sz += e[2]; n++; } }
  sx /= n; sz /= n;
  let cxx = 0, czz = 0, cxz = 0;
  for (const p of prims) { const pos = p.getAttribute('POSITION'); for (let i = 0; i < pos.getCount(); i++) { pos.getElement(i, e); const x = e[0] - sx, z = e[2] - sz; cxx += x * x; czz += z * z; cxz += x * z; } }
  // eigenvector of the smaller eigenvalue of [[cxx,cxz],[cxz,czz]]
  const tr = cxx + czz, det = cxx * czz - cxz * cxz;
  const lmin = tr / 2 - Math.sqrt(Math.max(0, (tr * tr) / 4 - det));
  let vx = cxz, vz = lmin - cxx;
  if (Math.abs(vx) + Math.abs(vz) < 1e-9) { vx = cxx <= czz ? 1 : 0; vz = cxx <= czz ? 0 : 1; }
  let yaw = Math.atan2(vz, vx); // angle of the axle from +X, rotating X towards Z
  if (yaw > Math.PI / 2) yaw -= Math.PI;
  if (yaw < -Math.PI / 2) yaw += Math.PI;
  return yaw;
}

// Pull wheel geometry out of the body into wheel_xx nodes.
//   select(node, mesh, prim) -> true when the whole primitive is wheel geometry
//   opts.axleGap: min gap (m) between triangle-centroid z clusters that splits axles
//   opts.unsteer: straighten wheels modelled at a steering angle (default true)
// Triangles are assigned to a wheel by side (x sign) and axle (z cluster).
//   opts.symmetrize: give each axle's left/right wheels mirrored x and a shared z
//     (straightening a steered wheel about its own centre leaves it a few cm off)
export function extractWheels(doc, select, { axleGap = 0.15, unsteer = true, symmetrize = true, log = true } = {}) {
  const root = doc.getRoot();
  const scene = root.listScenes()[0];
  const picked = [];
  for (const n of root.listNodes()) {
    const mesh = n.getMesh();
    if (!mesh) continue;
    for (const p of mesh.listPrimitives()) if (select(n, mesh, p)) picked.push({ n, mesh, p });
  }
  if (!picked.length) throw new Error('extractWheels: no wheel primitives selected');
  // triangle centroids
  const tris = [];
  const tv = [0, 0, 0], e = [0, 0, 0];
  for (const it of picked) {
    const pos = it.p.getAttribute('POSITION');
    const nt = triCount(it.p);
    it.side = new Int8Array(nt);
    it.axle = new Int16Array(nt);
    for (let t = 0; t < nt; t++) {
      triVerts(it.p, t, tv);
      let x = 0, z = 0;
      for (const v of tv) { pos.getElement(v, e); x += e[0] / 3; z += e[2] / 3; }
      tris.push({ it, t, x, z });
    }
  }
  const [bmn, bmx] = docBounds(doc);
  const cx = (bmn[0] + bmx[0]) / 2;
  // axle clusters along z
  const zs = tris.map((r) => r.z).sort((a, b) => a - b);
  const cuts = [];
  for (let i = 1; i < zs.length; i++) if (zs[i] - zs[i - 1] > axleGap) cuts.push((zs[i] + zs[i - 1]) / 2);
  const axleOf = (z) => { let a = 0; while (a < cuts.length && z > cuts[a]) a++; return a; };
  const nAxles = cuts.length + 1;
  for (const r of tris) { r.it.side[r.t] = r.x > cx ? 1 : -1; r.it.axle[r.t] = axleOf(r.z); }
  // axle 0 = rearmost; name front axle 'f', the rest 'r', 'r2', ... from the front backwards
  const axleName = (a) => {
    const fromFront = nAxles - 1 - a;
    return fromFront === 0 ? 'f' : fromFront === 1 ? 'r' : 'r' + fromFront;
  };
  const wheels = [];
  for (let a = 0; a < nAxles; a++) for (const side of [1, -1]) {
    const prims = [];
    for (const it of picked) {
      const keep = new Uint8Array(it.side.length);
      let any = false;
      for (let t = 0; t < keep.length; t++) if (it.side[t] === side && it.axle[t] === a) { keep[t] = 1; any = true; }
      if (!any) continue;
      const sp = subsetPrimitive(doc, it.p, keep);
      if (sp) prims.push(sp);
    }
    if (!prims.length) continue;
    const ax = axleName(a);
    const name = 'wheel_' + ax[0] + (side > 0 ? 'l' : 'r') + ax.slice(1);
    let mn = [1e9, 1e9, 1e9], mx = [-1e9, -1e9, -1e9];
    for (const p of prims) primBounds(p, mn, mx);
    let c = mn.map((v, k) => (v + mx[k]) / 2);
    let yaw = unsteer ? axleYaw(prims) : 0;
    if (Math.abs(yaw) < (2 * Math.PI) / 180) yaw = 0;
    if (yaw) {
      for (const p of prims) moveVerts(p, c, yaw, [0, 0, 0]);
      mn = [1e9, 1e9, 1e9]; mx = [-1e9, -1e9, -1e9];
      for (const p of prims) primBounds(p, mn, mx);
      c = mn.map((v, k) => (v + mx[k]) / 2);
    }
    for (const p of prims) moveVerts(p, [0, 0, 0], 0, [-c[0], -c[1], -c[2]]);
    const mesh = doc.createMesh(name);
    prims.forEach((p) => mesh.addPrimitive(p));
    const node = doc.createNode(name).setMesh(mesh).setTranslation(c);
    scene.addChild(node);
    const size = mx.map((v, k) => v - mn[k]);
    wheels.push({ name, center: c, size, yawDeg: (yaw * 180) / Math.PI });
    if (log) console.log(`  ${name}: centre ${c.map((v) => v.toFixed(3)).join(',')} size ${size.map((v) => v.toFixed(2)).join('x')}${yaw ? ` unsteered ${((yaw * 180) / Math.PI).toFixed(1)}deg` : ''}`);
  }
  if (symmetrize) {
    const byAxle = new Map();
    for (const w of wheels) { const k = w.name.replace(/^wheel_(.)[lr]/, '$1'); if (!byAxle.has(k)) byAxle.set(k, []); byAxle.get(k).push(w); }
    for (const pair of byAxle.values()) {
      if (pair.length !== 2) continue;
      const hx = (Math.abs(pair[0].center[0] - cx) + Math.abs(pair[1].center[0] - cx)) / 2;
      const z = (pair[0].center[2] + pair[1].center[2]) / 2, y = (pair[0].center[1] + pair[1].center[1]) / 2;
      for (const w of pair) {
        w.center = [cx + Math.sign(w.center[0] - cx) * hx, y, z];
        root.listNodes().find((n) => n.getName() === w.name).setTranslation(w.center);
      }
      if (log) console.log(`  axle ${pair[0].name.slice(6, 7)}: half-track ${hx.toFixed(3)} z ${z.toFixed(3)}`);
    }
  }
  // remove the extracted primitives from the body
  for (const it of picked) { it.mesh.removePrimitive(it.p); it.p.dispose(); }
  for (const m of root.listMeshes()) if (!m.listPrimitives().length) {
    for (const n of root.listNodes()) if (n.getMesh() === m) n.dispose();
    m.dispose();
  }
  return wheels;
}

// Re-centre the whole car: x/z on the body bbox centre, tyres (lowest point) on y = 0.
export function groundAndCentre(doc) {
  const [mn, mx] = docBounds(doc);
  const d = [-(mn[0] + mx[0]) / 2, -mn[1], -(mn[2] + mx[2]) / 2];
  for (const n of doc.getRoot().listNodes()) {
    if (!n.getMesh()) continue;
    if (/^wheel_/.test(n.getName())) {
      const t = n.getTranslation();
      n.setTranslation([t[0] + d[0], t[1] + d[1], t[2] + d[2]]);
    } else for (const p of n.getMesh().listPrimitives()) moveVerts(p, [0, 0, 0], 0, d);
  }
}

// Simplify body + wheels (wheels at a gentler ratio) and join the body into one
// mesh per material. Body nodes/meshes are unnamed so join() merges them; the
// named wheel nodes survive (keepNamed).
export async function simplifyAndJoin(doc, { ratio = 0.5, error = 0.002, wheelRatio = null } = {}) {
  const root = doc.getRoot();
  for (const n of root.listNodes()) {
    if (/^wheel_/.test(n.getName())) continue;
    n.setName('');
    if (n.getMesh()) n.getMesh().setName('');
  }
  await doc.transform(dedup(), weld());
  await MeshoptSimplifier.ready;
  for (const n of root.listNodes()) {
    const mesh = n.getMesh();
    if (!mesh) continue;
    const r = /^wheel_/.test(n.getName()) ? (wheelRatio ?? ratio) : ratio;
    if (r >= 1) continue;
    for (const p of mesh.listPrimitives()) {
      simplifyPrimitive(p, { simplifier: MeshoptSimplifier, ratio: r, error });
      if (!p.getIndices() || p.getIndices().getCount() === 0) { mesh.removePrimitive(p); p.dispose(); }
    }
  }
  await doc.transform(join({ keepNamed: true }), prune(), dedup());
}

// ---------------------------------------------------------------- textures
// Opaque textures -> JPEG, textures read for alpha -> PNG; everything <= max px.
export async function encodeTextures(doc, { max = 1024, normalMax = null, quality = 82 } = {}) {
  const root = doc.getRoot();
  for (const tex of root.listTextures()) {
    const users = root.listMaterials();
    let alpha = false, isNormal = false;
    for (const m of users) {
      if (m.getBaseColorTexture() === tex && m.getAlphaMode() !== 'OPAQUE') alpha = true;
      if (m.getNormalTexture() === tex) isNormal = true;
    }
    const lim = isNormal && normalMax ? normalMax : max;
    const img = sharp(tex.getImage());
    const meta = await img.metadata();
    let pipe = img;
    if (meta.width > lim || meta.height > lim) pipe = pipe.resize(lim, lim, { fit: 'inside' });
    let out, mime;
    if (alpha) { out = await pipe.png({ compressionLevel: 9, palette: false }).toBuffer(); mime = 'image/png'; }
    else { out = await pipe.removeAlpha().jpeg({ quality, mozjpeg: true }).toBuffer(); mime = 'image/jpeg'; }
    if (!alpha || out.length < tex.getImage().length || meta.width > lim) {
      tex.setImage(out).setMimeType(mime);
      tex.setURI('');
    }
  }
}

// ---------------------------------------------------------------- report + checks
const BRAND = /porsche|carrera|stuttgart|911|tesla|model ?3|mercedes|benz|sprinter|toyota|prius|ford|chevrolet|khronos|3d commerce|sketchfab/i;
export function checkCar(doc, label) {
  const root = doc.getRoot();
  const problems = [];
  if (root.listExtensionsUsed().length) problems.push('extensions: ' + root.listExtensionsUsed().map((e) => e.extensionName).join(','));
  const names = [];
  root.listNodes().forEach((n) => names.push('node:' + n.getName()));
  root.listMeshes().forEach((n) => names.push('mesh:' + n.getName()));
  root.listMaterials().forEach((n) => names.push('mat:' + n.getName()));
  root.listTextures().forEach((n) => names.push('tex:' + n.getName() + ' ' + n.getURI()));
  root.listScenes().forEach((n) => names.push('scene:' + n.getName()));
  for (const s of names) if (BRAND.test(s)) problems.push('brand name ' + s);
  const wheels = root.listNodes().filter((n) => /^wheel_[fr][lr]\d*$/.test(n.getName()));
  if (wheels.length < 4) problems.push('only ' + wheels.length + ' wheel nodes');
  if (!root.listMaterials().some((m) => m.getName() === 'paint')) console.log('  note: no paint material (not recolourable)');
  for (const t of root.listTextures()) { const s = t.getSize(); if (s && (s[0] > 1024 || s[1] > 1024)) problems.push('texture > 1024: ' + t.getName()); }
  let tris = 0;
  for (const m of root.listMeshes()) for (const p of m.listPrimitives()) tris += triCount(p);
  const [mn, mx] = docBounds(doc);
  console.log(`  ${label}: ${tris} tris, ${root.listMeshes().length} meshes, ${root.listMaterials().length} materials, ${root.listTextures().length} textures, size ${mx.map((v, k) => (v - mn[k]).toFixed(2)).join('x')} (min y ${mn[1].toFixed(3)})`);
  if (problems.length) { console.error('  PROBLEMS:', problems.join('; ')); process.exitCode = 1; }
  return { tris };
}

export function setCredit(doc, sceneName, copyright) {
  const root = doc.getRoot();
  root.listScenes().forEach((s) => s.setName(sceneName));
  root.getAsset().copyright = copyright;
  root.getAsset().generator = 'Crimson Coast tools/models (glTF-Transform)';
  for (const e of root.listExtensionsUsed()) e.dispose();
}

// The game has no environment map, so fully metallic PBR materials render
// almost black. Cap metalness (the factor scales any metallic texture too).
export function tameMetal(doc, max = 0.4) {
  for (const m of doc.getRoot().listMaterials()) {
    // glass and light lenses read as dark mirrors when metallic
    const lim = m.getAlphaMode() === 'BLEND' ? 0.1 : max;
    if (m.getMetallicFactor() > lim) m.setMetallicFactor(lim);
  }
}
